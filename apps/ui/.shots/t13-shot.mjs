import { chromium } from "playwright";
const token = "sse-test-token";
const browser = await chromium.launch({ args: ["--no-sandbox", "--disable-dev-shm-usage"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
await context.addInitScript((t) => { window.localStorage.setItem("mailcollect.token", t); }, token);
const page = await context.newPage();
await page.goto("http://localhost:4173", { waitUntil: "networkidle" });
await page.getByText("已连接服务").first().waitFor({ timeout: 20000 });
await page.locator(".nav-item").filter({ hasText: "设置" }).click();
await page.waitForTimeout(400);
await page.locator(".page-scroll").evaluate((node) => { node.scrollTop = 430; });
await page.waitForTimeout(300);
await page.locator("button").filter({ hasText: "添加账号" }).click();
await page.waitForTimeout(250);
await page.locator("#account-provider").selectOption("graph");
await page.waitForTimeout(250);
await page.locator("#account-email").fill("zhangsan@outlook.com");
await page.locator("#account-client-id").fill("11111111-2222-3333-4444-555555555555");
await page.locator("#account-tenant").fill("contoso.onmicrosoft.com");
await page.waitForTimeout(300);
await page.screenshot({ path: "apps/ui/.shots/13-graph-account-form.png" });
console.log("SHOT 13-graph-account-form");
await browser.close();
